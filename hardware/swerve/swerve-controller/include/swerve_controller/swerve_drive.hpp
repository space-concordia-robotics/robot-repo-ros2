#pragma once

/**
 * @file swerve_drive.hpp
 * @brief ROS 2 Control (`controller_interface::ControllerInterface`) plugin for a 4-Wheel Independent
 *        Steering (4WIS) swerve drive robot.
 *
 * Subscribes to `~/cmd_vel` (`geometry_msgs::msg::TwistStamped`), applies velocity/acceleration/jerk
 * rate limiting, computes per-module wheel speeds and steering angles via `SwerveKinematics`, and
 * writes commands to the hardware interfaces in real time.
 */

#include <memory>
#include <control_toolbox/rate_limiter.hpp>
#include <controller_interface/controller_interface.hpp>
#include <realtime_tools/realtime_buffer.hpp>
#include <ros2_fmt_logger/logger.hpp>
#include <geometry_msgs/msg/twist_stamped.hpp>

#include "swerve_kinematics.hpp"
#include "swerve_controller/swerve_controller_parameters.hpp"

namespace swerve_controller {
    /**
     * @brief Lifecycle-managed `ros2_control` controller for a 4-module swerve drivetrain.
     */
    class SwerveController : public controller_interface::ControllerInterface {
        using TwistStamped = geometry_msgs::msg::TwistStamped;

    public:
        SwerveController();

        ~SwerveController() override;

        /**
         * @brief Initializes the controller node logger and loads generated ROS 2 parameters.
         */
        controller_interface::CallbackReturn on_init() override;

        /**
         * @brief Declares the required hardware command interfaces:
         *        4 steering position interfaces (`<steering_joint>/position`) and
         *        4 wheel velocity interfaces (`<wheel_joint>/velocity`).
         */
        controller_interface::InterfaceConfiguration command_interface_configuration() const override;

        /**
         * @brief Declares the required hardware state feedback interfaces:
         *        4 steering position state interfaces (`<steering_joint>/position`) and
         *        4 wheel velocity state interfaces (`<wheel_joint>/velocity`).
         */
        controller_interface::InterfaceConfiguration state_interface_configuration() const override;

        /**
         * @brief Configures module geometry, constructs the `SwerveKinematics` solver,
         *        creates the `~/cmd_vel` subscriber, and initializes velocity rate limiters.
         */
        controller_interface::CallbackReturn on_configure(const rclcpp_lifecycle::State& previous_state) override;

        /**
         * @brief Claims and binds loaned hardware state and command interfaces for all 4 swerve modules,
         *        and marks the command subscriber as active.
         */
        controller_interface::CallbackReturn on_activate(const rclcpp_lifecycle::State& previous_state) override;

        /**
         * @brief Deactivates command processing and releases module hardware handles.
         */
        controller_interface::CallbackReturn on_deactivate(const rclcpp_lifecycle::State& previous_state) override;

        /**
         * @brief Real-time control loop step called at the controller manager's update rate.
         *
         * Reads the latest `TwistStamped` command from the real-time buffer, applies rate limiters,
         * reads current steering angles from state interfaces, solves inverse kinematics, and writes
         * target steering positions (rad) and wheel angular velocities (rad/s) to hardware.
         */
        controller_interface::return_type update(const rclcpp::Time& time, const rclcpp::Duration& period) override;

    private:
        /// Formatted ROS 2 logger wrapper (`ros2_fmt_logger`).
        std::shared_ptr<ros2_fmt_logger::Logger> logger;

        /// Parameter listener and parameter struct generated by `generate_parameter_library`.
        std::shared_ptr<ParamListener> param_listener;
        Params params;

        // TODO 2026-10-07 (Will Free): can I avoid the pointer here?
        /// Inverse kinematics solver instance initialized during `on_configure()`.
        std::unique_ptr<SwerveKinematics> kinematics = nullptr;

        /// Distance between front and rear wheel axles (m).
        double wheelbase = 1.0;
        /// Distance between left and right wheels on the same axle (m).
        double track_width = 1.0;
        /// Radius of each drive wheel (m), used to convert linear speed (m/s) to angular velocity (rad/s).
        double wheel_radius = 0.1;

        /// Flag indicating whether the controller is currently active and accepting `cmd_vel` messages.
        bool subscription_active = false;

        /// ROS 2 subscription for incoming chassis velocity commands (`~/cmd_vel`).
        rclcpp::Subscription<TwistStamped>::SharedPtr cmd_vel_subscription;

        // TODO 2026-10-07 (Will Free): replace with RealtimeThreadSafeBox
        /// Lock-free / real-time safe buffer transferring `TwistStamped` messages from the ROS subscriber thread to `update()`.
        realtime_tools::RealtimeBuffer<TwistStamped> velocity_message;

        /**
         * @brief Joint names for a single swerve module.
         */
        struct SwerveModuleJoints {
            std::string steering_joint; ///< Name of the revolute/continuous steering joint
            std::string wheel_joint;    ///< Name of the continuous drive wheel joint
        };

        /// Configured joint names for the 4 modules.
        std::array<SwerveModuleJoints, 4> joints;

        /**
         * @brief References to the loaned `ros2_control` state and command interfaces for one swerve module.
         */
        struct SwerveModuleHandle {
            std::reference_wrapper<const hardware_interface::LoanedStateInterface> steering_feedback; ///< Current steering angle (rad)
            std::reference_wrapper<hardware_interface::LoanedCommandInterface> steering_position;     ///< Target steering angle (rad)
            std::reference_wrapper<const hardware_interface::LoanedStateInterface> wheel_feedback;    ///< Current wheel angular velocity (rad/s)
            std::reference_wrapper<hardware_interface::LoanedCommandInterface> wheel_velocity;        ///< Target wheel angular velocity (rad/s)
        };

        // I want to use an std::array<SwerveModuleHandle, 4> here, but can't because it requires all the structs be initialized in the constructor
        /// Active hardware interface handles for the 4 swerve modules (ordered: FL, FR, RL, RR).
        std::vector<SwerveModuleHandle> modules;

        /// History of the last two rate-limited commands `[(v_{k-2}, w_{k-2}), (v_{k-1}, w_{k-1})]` required for acceleration/jerk limiting.
        std::array<std::tuple<Eigen::Vector2d, double>, 2> previous_two_commands;

        /// Velocity, acceleration, and jerk rate limiter for longitudinal velocity (`linear.x`).
        control_toolbox::RateLimiter<double> limiter_linear_x;
        /// Velocity, acceleration, and jerk rate limiter for lateral velocity (`linear.y`).
        control_toolbox::RateLimiter<double> limiter_linear_y;
        /// Velocity, acceleration, and jerk rate limiter for yaw angular velocity (`angular.z`).
        control_toolbox::RateLimiter<double> limiter_angular;
    };
}
